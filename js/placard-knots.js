const paths = new Map();
export function drawCelticKnot(ctx, kind, x, y, width, color) {
  const art = drawings[kind];
  let shape = paths.get(kind);
  if (!shape) {
    shape = { loops: art.loops.map(d => new Path2D(d)),
      cuts: new Path2D(art.cuts), bridges: new Path2D(art.bridges) };
    paths.set(kind, shape);
  }
  ctx.save(); ctx.translate(x, y);
  ctx.scale(width / art.span, -width / art.span);
  ctx.translate(-art.cx, -art.cy);
  ctx.lineJoin = 'round'; ctx.lineCap = 'butt'; ctx.strokeStyle = color;
  const clear = path => {
    ctx.globalCompositeOperation = 'destination-out';
    ctx.lineWidth = art.clearance; ctx.stroke(path);
  };
  const paint = path => {
    ctx.globalCompositeOperation = 'source-over';
    ctx.lineWidth = art.strand; ctx.stroke(path);
  };
  for (const path of shape.loops) { clear(path); paint(path); }
  clear(shape.cuts); paint(shape.bridges);
  ctx.restore();
}
