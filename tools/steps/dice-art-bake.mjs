import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

// Offline images of the actual meshes. Runtime needs only the visible files;
// recipe edits or missing files retain the on-demand rendering fallback.
export default async function run(stage) {
  const root=fileURLToPath(new URL('../../',import.meta.url));
  const dir=root+'models/dice-art/';mkdirSync(dir,{recursive:true});
  const a=await stage.tab('localhost','Portraits');
  const rows=await a.eval(`(async()=>{
    const {SETS}=await import('/js/themes.js'),{portraitSignature}=await import('/js/diceart-recipe.js');
    return ['std','shroud',...Object.keys(SETS)].map(id=>({id,signature:portraitSignature(SETS[id]||id)}));
  })()`);
  for(const {id} of rows){
    const data=await a.eval(`(async()=>{
      const {dieArtURL,bustArt,releaseDieArtRenderer}=await import('/js/diceart.js');
      const {DIE_TYPES,bustDie}=await import('/js/dice.js');
      const canvas=document.createElement('canvas');canvas.width=canvas.height=192;
      const ctx=canvas.getContext('2d'),out={};
      for(const type of DIE_TYPES){
        const url=dieArtURL(type,${JSON.stringify(id)});if(!url)throw new Error('No portrait for '+type);
        const img=new Image();img.src=url;await img.decode();
        ctx.clearRect(0,0,192,192);ctx.drawImage(img,0,0);
        out[type]=canvas.toDataURL('image/webp',.94).split(',')[1];
      }
      releaseDieArtRenderer();bustArt(${JSON.stringify(id)});
      if(${JSON.stringify(id)}!=='std')bustDie(${JSON.stringify(id)});
      return out;
    })()`);
    for(const [type,bytes] of Object.entries(data))writeFileSync(`${dir}${id}.${type}.webp`,Buffer.from(bytes,'base64'));
    console.log('portraits '+id);
  }
  const sources=['js/diceart.js','js/dice.js','js/themes.js'];
  const digest=createHash('sha256');for(const file of sources)digest.update(readFileSync(root+file));
  writeFileSync(root+'js/diceart-manifest.js',`/* Copyright 2026 The Dice Table Authors — SPDX-License-Identifier: Apache-2.0 */\n// Generated by tools/steps/dice-art-bake.mjs.\nexport const PORTRAIT_SOURCES = ${JSON.stringify(sources)};\nexport const PORTRAIT_RENDERER = '${digest.digest('hex')}';\nexport const PORTRAIT_RECIPES = ${JSON.stringify(Object.fromEntries(rows.map(r=>[r.id,r.signature])),null,2)};\n`);
}
